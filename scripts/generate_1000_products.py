def gen_skus(sub, price, cat):
    if cat in ("服饰运动", "运动户外"):
        sizes = ["S","M","L","XL"]
        colors = ["黑色","白色","灰色","深蓝"]
        skus = []
        for s in random.sample(sizes, min(3, len(sizes))):
            for c in random.sample(colors, min(2, len(colors))):
                skus.append({"尺码": s, "颜色": c})
        return skus[:6]
    elif cat in ("美妆护肤", "个护清洁"):
        opts = [{"规格":"标准装"},{"规格":"加大装","_p":round(price*1.6,0)},{"规格":"旅行装","_p":round(price*0.5,0)}]
        return random.sample(opts, min(2, len(opts)))
    elif cat == "数码电子":
        colors = ["黑色","白色","银色","蓝色"]
        return [{"颜色": c} for c in random.sample(colors, min(3, len(colors)))]
    elif cat == "食品生活":
        opts = [{"规格":"单份装"},{"规格":"家庭装","_p":round(price*1.8,0)},{"规格":"礼盒装","_p":round(price*2.2,0)}]
        return random.sample(opts, min(2, len(opts)))
    else:
        colors = ["白色","黑色","灰色","粉色"]
        return [{"颜色": c} for c in random.sample(colors, min(2, len(colors)))]

def gen_product(pid, brand, title, cat, sub, price, img_dir):
    skus = gen_skus(sub, price, cat)
    mkt = gen_marketing(brand, title, sub, price, cat)
    faqs = get_faqs(sub, brand)
    revs = [gen_review(sub, brand, price) for _ in range(random.randint(3, 4))]
    return build(pid, brand, title, cat, sub, price, skus, mkt, faqs, revs, img_dir)

