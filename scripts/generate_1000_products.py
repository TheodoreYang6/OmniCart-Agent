def get_faqs(sub, brand):
    pool = FAQ_POOL.get(sub, DEFAULT_FAQ)
    result = []
    for q, a in pool:
        try:
            result.append((q, a.format(brand=brand, sub=sub)))
        except (KeyError, IndexError):
            # Replace known vars, strip unknown {xxx} patterns
            txt = a.replace("{brand}", brand).replace("{sub}", sub)
            txt = re.sub(r'\{[^}]+\}', '', txt)
            result.append((q, txt))
    return result[:3]

