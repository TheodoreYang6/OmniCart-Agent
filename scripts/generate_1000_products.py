# ============ MAIN GENERATION ============
def generate_category(cat_name, cfg):
    products = []
    prefix, start, target = cfg["prefix"], cfg["start"], cfg["target"]
    img_dir, brands, subs = cfg["img"], cfg["brands"], cfg["subs"]
    price_ranges = cfg["prices"]
    existing = target - start + 1 if start > 1 else target
    # For existing categories, subtract already existing products
    if start > 1:
        existing_count = start - 1
        need = target - existing_count
    else:
        need = target

    # Use detailed templates for beauty (first 20)
    templates = []
    if cat_name == "美妆护肤":
        templates = BEAUTY_T

    idx = start
    # First: use detailed templates
    for t in templates:
        if idx > target: break
        pid = f"{prefix}_{idx:03d}"
        brand, title, sub, price, skus_spec, mkt, faqs, revs = t
        p = build(pid, brand, title, cat_name, sub, price, skus_spec, mkt, faqs, revs, img_dir)
        products.append(p)
        idx += 1

    # Then: generate remaining with real brands
    while idx <= target:
        brand = random.choice(brands)
        sub = random.choice(subs)
        pr = random.choice(price_ranges)
        price = round(random.uniform(pr[0], pr[1]), 0)
        title = gen_title(brand, sub, cat_name)
        pid = f"{prefix}_{idx:03d}"
        p = gen_product(pid, brand, title, cat_name, sub, price, img_dir)
        products.append(p)
        idx += 1

    return products

