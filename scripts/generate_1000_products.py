def build(pid, brand, title, cat, sub, price, skus_spec, mkt, faqs, revs, img_dir):
    skus = []
    for i, s in enumerate(skus_spec, 1):
        sku = {"sku_id": f"s_{pid}_{i}", "properties": {}, "price": price}
        for k, v in s.items():
            if k == "_p": sku["price"] = v
            else: sku["properties"][k] = v
        skus.append(sku)
    return {
        "product_id": pid, "title": title, "brand": brand,
        "category": cat, "sub_category": sub, "base_price": price,
        "image_path": f"{img_dir}/images/{pid}.jpg", "skus": skus,
        "rag_knowledge": {
            "marketing_description": mkt,
            "official_faq": [{"question": q, "answer": a} for q, a in faqs],
            "user_reviews": [{"nickname": n, "rating": r, "content": c} for n, r, c in revs],
        },
    }

def write_all(products, data_dir):
    data_dir.mkdir(parents=True, exist_ok=True)
    for p in products:
        fp = data_dir / f"{p['product_id']}.json"
        fp.write_text(json.dumps(p, ensure_ascii=False, indent=2), encoding="utf-8")
    return len(products)

