def resolve(sub_category: str | None) -> tuple[str, ...]:
    """把（可能是口语的）子品类词映射为数据集真实值元组；无映射则原样返回。"""
    if not sub_category:
        return ()
    key = sub_category.strip().lower()
    hit = ALIASES.get(key)
    if hit:
        return hit
    return (sub_category.strip(),)


def infer_from_query(query: str, known: set[str] | None = None) -> tuple[str, ...]:
    """从 query 中推断明确的子品类（最长匹配优先）。

    known: 数据集真实 sub_category 全集，用于兜住别名表未收录的原值
    （如"帐篷""台灯"直接出现在 query 里）。

    只在 query 含明确品类名词时返回非空 —— 模糊需求（"补水产品""换季用什么"）
    返回空元组，由上层走原语义检索路径（宁不过滤也不要错过滤）。
    """
    if not query:
        return ()
    q = query.strip().lower()
    candidates: list[tuple[int, tuple[str, ...]]] = []
    for word, values in ALIASES.items():
        if word in q:
            candidates.append((len(word), values))
    for name in known or ():
        n = name.strip().lower()
        if len(n) >= 2 and n in q:
            candidates.append((len(n), (name,)))
    if not candidates:
        return ()
    candidates.sort(key=lambda x: -x[0])
    best_len = candidates[0][0]
    # 同长度的多个命中取并集（如"耳机"命中真无线+头戴式）
    merged: list[str] = []
    for ln, values in candidates:
        if ln != best_len:
            break
        for v in values:
            if v not in merged:
                merged.append(v)
    return tuple(merged)
