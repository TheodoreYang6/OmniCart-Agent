def expand_brand_aliases(tags: list[str]) -> list[str]:
    """将排除标签中的品牌名展开为双语版本，确保中英文都能匹配。"""
    expanded = list(tags)
    for tag in tags:
        alias = BRAND_ALIASES.get(tag.lower())
        if alias and alias not in expanded:
            expanded.append(alias)
    return expanded

